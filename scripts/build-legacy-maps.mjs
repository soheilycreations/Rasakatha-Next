// Turns supabase/data/legacy-urls.json (see extract-legacy-urls.mjs) into the
// two lookups the redirect handlers use. Read-only against Supabase.
//
//   node --env-file=.env.local scripts/build-legacy-maps.mjs
//
// Writes:
//   src/lib/data/legacy-slugs.json       { "<book id>": "<old woocommerce slug>" }
//   src/lib/data/legacy-categories.json  { "<old product_cat slug>": "<our category name>" }
//   supabase/data/legacy-slugs.sql       UPDATE statements for books.legacy_slug (NOT run automatically)
import fs from "node:fs";
import { createClient } from "@supabase/supabase-js";

const legacy = JSON.parse(fs.readFileSync("supabase/data/legacy-urls.json", "utf8"));
const sb = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });

const decode = (s) => {
  try {
    return decodeURIComponent(s).normalize("NFC");
  } catch {
    return s;
  }
};

const books = [];
for (let from = 0; ; from += 1000) {
  const { data, error } = await sb.from("books").select("id,category").range(from, from + 999);
  if (error) throw error;
  books.push(...data);
  if (data.length < 1000) break;
}
const ourCategory = new Map(books.map((b) => [b.id, b.category]));

// --- product slugs (published products that exist in our catalog) ---
const slugs = {};
let missing = 0;
for (const p of legacy.products) {
  if (p.status !== "publish") continue;
  if (!ourCategory.has(p.id)) {
    missing++;
    continue;
  }
  slugs[p.id] = decode(p.slug);
}

// --- categories: vote by the products each old category contains ---
const termsByTt = new Map(legacy.categories.map((c) => [c.ttId, c]));
const votes = new Map(); // ttId -> Map(ourCategory -> count)
for (const [productId, ttIds] of Object.entries(legacy.productCategories)) {
  const cat = ourCategory.get(productId);
  if (!cat) continue;
  for (const tt of ttIds) {
    const m = votes.get(tt) ?? new Map();
    m.set(cat, (m.get(cat) ?? 0) + 1);
    votes.set(tt, m);
  }
}
const categories = {};
let weak = 0;
for (const [tt, m] of votes) {
  const term = termsByTt.get(tt);
  if (!term) continue;
  const total = [...m.values()].reduce((a, b) => a + b, 0);
  const [best, count] = [...m.entries()].sort((a, b) => b[1] - a[1])[0];
  // Only redirect to a specific category when it clearly dominates; otherwise
  // the old category was a cross-cutting one (e.g. "Sinhala") and falls back to /categories.
  if (count / total >= 0.6 && best !== "Other") categories[decode(term.slug)] = best;
  else weak++;
}

fs.writeFileSync("src/lib/data/legacy-slugs.json", JSON.stringify(slugs));
fs.writeFileSync("src/lib/data/legacy-categories.json", JSON.stringify(categories, null, 1));

const esc = (s) => s.replace(/'/g, "''");
const sql =
  "-- Generated by scripts/build-legacy-maps.mjs. Run supabase/legacy-slug.sql first.\n" +
  Object.entries(slugs)
    .map(([id, slug]) => `update books set legacy_slug = '${esc(slug)}' where id = '${id}';`)
    .join("\n") +
  "\n";
fs.writeFileSync("supabase/data/legacy-slugs.sql", sql);

console.log({
  ourBooks: books.length,
  publishedLegacyProducts: Object.keys(slugs).length,
  publishedProductsNotInOurCatalog: missing,
  categoryMappings: Object.keys(categories).length,
  weakCategoriesFallingBackToIndex: weak,
});
